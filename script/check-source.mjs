import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=name=>fs.readFileSync(new URL('../src/'+name,import.meta.url),'utf8');
const app=read('App.tsx'),store=read('store.tsx'),seed=read('seed.ts');
const defined=[...app.matchAll(/id:'([a-z]+)',label:/g)].map(m=>m[1]);
const unique=new Set(defined);
assert.equal(defined.length,20,'20 applications must be defined');
assert.equal(unique.size,20,'app identifiers must be unique');
const required=['whatsapp','instagram','photos','camera','phone','contacts','mail','calendar','notes','safari','music','maps','calculator','files','settings','wallet','weather','reminders','clock','fitness'];
for(const id of required)assert(unique.has(id),`Missing app: ${id}`);
assert(app.includes("next==='7777'"),'Working passcode check must exist');
assert(app.includes('<LockScreen')&&app.includes('<HomeScreen'),'Lock and home screens exist');
for(const person of ['Freya','Noah','Mama','Aiden','Catherine'])assert(seed.includes(person),`Missing story character ${person}`);
assert(store.includes('localStorage.setItem'),'Local state persistence must exist');
assert(read('AppsSocial.tsx').includes('setChats'),'WhatsApp send must update state');
assert(read('AppsProductivity.tsx').includes('setNotes'),'Notes editing must update state');
assert(read('AppsUtilities.tsx').includes("value==='='"),'Calculator equals handler must exist');
console.log('PASS: 20 apps, core navigation, passcode, story, persistence, and key handlers.');
console.log('Note: This checks source integrity, not real-browser interactions.');
